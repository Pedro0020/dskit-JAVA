"""Adopt dskit control-plane files into an existing Java project.

The application scaffold is never generated by this command. Detection is
conservative: ambiguous values are reported and must be supplied explicitly.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import asdict, dataclass
from pathlib import Path


@dataclass
class ProjectFacts:
    build_tool: str | None = None
    java_version: str | None = None
    base_package: str | None = None
    framework: str | None = None
    db: str = "none"
    migrations: str = "none"


ADOPT_EXCLUDES = (
    "/src", "/pom.xml", "/mvnw", "/mvnw.cmd", "/.mvn", "/build.gradle",
    "/build.gradle.kts", "/settings.gradle", "/settings.gradle.kts", "/gradle",
    "/gradlew", "/gradlew.bat", "/README.md", "/CHANGELOG.md", "/LICENSE",
    "/SECURITY.md", "/CONTRIBUTING.md", "/Makefile", "/.gitignore",
)


def _text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def detect(root: Path) -> ProjectFacts:
    pom = _text(root / "pom.xml")
    gradle = _text(root / "build.gradle") + _text(root / "build.gradle.kts")
    facts = ProjectFacts()
    if (root / "pom.xml").exists():
        facts.build_tool = "maven"
    elif (root / "build.gradle").exists() or (root / "build.gradle.kts").exists():
        facts.build_tool = "gradle"

    build = pom + "\n" + gradle
    version = re.search(
        r"<(?:java\.version|maven\.compiler\.release)>\s*([0-9]+)"
        r"|sourceCompatibility\s*[=:]\s*['\"]?([0-9]+)"
        r"|JavaLanguageVersion\.of\((\d+)\)",
        build,
    )
    if version:
        facts.java_version = next(group for group in version.groups() if group)

    packages = []
    for source in (root / "src" / "main" / "java",):
        if source.exists():
            packages = re.findall(r"^\s*package\s+([a-z][\w]*(?:\.[a-z][\w]*)+)\s*;", "\n".join(
                _text(p) for p in source.rglob("*.java")
            ), re.MULTILINE)
    if packages:
        facts.base_package = max(set(packages), key=packages.count)

    has_batch = "spring-batch" in build or "spring_batch" in build or "starter-batch" in build
    has_web = "starter-web" in build or "spring-web" in build
    if has_batch and has_web:
        facts.framework = "spring-boot-web+batch"
    elif has_batch:
        facts.framework = "spring-boot-batch"
    elif has_web:
        facts.framework = "spring-boot"

    if "postgresql" in build:
        facts.db = "postgres"
    elif "mysql-connector" in build or "mysql:mysql-connector" in build:
        facts.db = "mysql"
    elif "h2database" in build:
        facts.db = "h2"
    if "flyway" in build:
        facts.migrations = "flyway"
    elif "liquibase" in build:
        facts.migrations = "liquibase"
    return facts


def _yaml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def answers(facts: ProjectFacts, overrides: dict[str, str]) -> str:
    values = asdict(facts)
    values.update(overrides)
    missing = [key for key in ("build_tool", "java_version", "base_package", "framework") if not values.get(key)]
    if missing:
        raise ValueError("No se pudieron detectar: " + ", ".join(missing) + ". Usa --" + " --".join(missing))
    values.update({"language": "java", "adopt_existing": True, "proyecto_perfil": "manual"})
    return "\n".join(f"{key}: {_yaml_value(value)}" for key, value in values.items()) + "\n"


def run(root: Path, template: Path, data_file: Path, dry_run: bool) -> int:
    copier = [shutil.which("copier") or "copier"]
    if copier == ["copier"] and not shutil.which("copier"):
        copier = ["uv", "run", "python", "-m", "copier"]
    command = [
        *copier, "copy", "--trust", "--force", "--skip-tasks",
        "--data-file", str(data_file),
        str(template), str(root),
    ]
    for pattern in ADOPT_EXCLUDES:
        command[command.index(str(template)) : command.index(str(template))] = ["--exclude", pattern]
    print(" ".join(command))
    if dry_run:
        return 0
    completed = subprocess.run(command, cwd=template)
    return completed.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", type=Path)
    parser.add_argument("--template", type=Path, default=Path(__file__).parents[1])
    parser.add_argument("--dry-run", action="store_true")
    for key in ("build-tool", "java-version", "base-package", "framework", "db", "migrations"):
        parser.add_argument("--" + key, dest=key.replace("-", "_"))
    args = parser.parse_args(argv)
    root = args.project.resolve()
    facts = detect(root)
    overrides = {key: getattr(args, key) for key in (
        "build_tool", "java_version", "base_package", "framework", "db", "migrations"
    ) if getattr(args, key)}
    try:
        content = answers(facts, overrides)
    except ValueError as exc:
        parser.error(str(exc))
    data_file = root / ".dskit-adopt-answers.yml"
    print("Detectado:", asdict(facts))
    if args.dry_run:
        print(content, end="")
        return run(root, args.template.resolve(), data_file, True)
    data_file.write_text(content, encoding="utf-8")
    try:
        result = run(root, args.template.resolve(), data_file, False)
        if result:
            return result
        _write_adoption_backlog(root, facts)
        answers_path = root / ".copier-answers.yml"
        with answers_path.open("a", encoding="utf-8") as fh:
            fh.write("adopt_existing: true\n")
        return 0
    finally:
        data_file.unlink(missing_ok=True)


